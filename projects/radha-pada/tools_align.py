def syl(s):  # aksharas: consonants not followed by virama + independent vowels
    n=0; cs=list(s)
    for i,c in enumerate(cs):
        o=ord(c)
        if 0x0B15<=o<=0x0B39 or o in (0x0B5C,0x0B5D,0x0B5F,0x0B71):
            if not (i+1<len(cs) and cs[i+1]=='୍'): n+=1
        elif 0x0B05<=o<=0x0B14: n+=1
    return n
